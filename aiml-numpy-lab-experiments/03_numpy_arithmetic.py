import numpy as np

a = np.array([1, 2, 3])
b = np.array([(1.5, 2, 3), (4, 5, 6)], dtype=float)

print("a - b:")
print(a - b)
print("np.subtract(a, b):")
print(np.subtract(a, b))
print("b + a:")
print(b + a)
print("np.add(b, a):")
print(np.add(b, a))
print("a / b:")
print(a / b)
print("np.divide(a, b):")
print(np.divide(a, b))
print("a * b:")
print(a * b)
print("np.multiply(a, b):")
print(np.multiply(a, b))
print("np.exp(b):")
print(np.exp(b))
print("np.sqrt(b):")
print(np.sqrt(b))
print("np.sin(a):")
print(np.sin(a))
print("np.cos(b):")
print(np.cos(b))
print("np.log(a):")
print(np.log(a))

e = np.full((2, 2), 7)
